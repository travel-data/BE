-- 13. TourCourseItem
-- 관광 코스에 포함되는 관광지 또는 주변 장소
--
-- spot_id:
--   관광지 아이템일 때 사용
--
-- tour_spot_nearby_course_id:
--   카페, 음식점, 숙박 시설 등의 주변 장소일 때 사용
--
-- 두 컬럼 중 정확히 하나만 값이 있어야 한다.
-- =========================================================

CREATE TABLE IF NOT EXISTS public."TourCourseItem"
(
    item_id                    int8 GENERATED BY DEFAULT AS IDENTITY,
    tour_course_id             int8 NOT NULL,

    spot_id                    int8 NULL,
    tour_spot_nearby_course_id int8 NULL,

    day_number                int4 NOT NULL DEFAULT 1,
    item_order                 int4 NOT NULL,
    transport_type             varchar(10) NULL,
    status                     varchar(20) NOT NULL DEFAULT 'PENDING',

    CONSTRAINT "PK_TOURCOURSEITEM"
        PRIMARY KEY (item_id),

    CONSTRAINT "FK_TOURCOURSEITEM_TOURCOURSE"
        FOREIGN KEY (tour_course_id)
        REFERENCES public."TourCourse" (tour_course_id)
        ON DELETE CASCADE,

    CONSTRAINT "FK_TOURCOURSEITEM_TOURSPOT"
        FOREIGN KEY (spot_id)
        REFERENCES public."TourSpot" (spot_id)
        ON DELETE RESTRICT,

    CONSTRAINT "FK_TOURCOURSEITEM_NEARBYPLACE"
        FOREIGN KEY (tour_spot_nearby_course_id)
        REFERENCES public."TourSpotNearbyPlace"
            (tour_spot_nearby_course_id)
        ON DELETE RESTRICT,

    CONSTRAINT "UK_TOURCOURSEITEM_DAY_ORDER"
        UNIQUE (tour_course_id, day_number, item_order),

    CONSTRAINT "CK_TOURCOURSEITEM_TARGET"
        CHECK (
            (
                spot_id IS NOT NULL
                AND tour_spot_nearby_course_id IS NULL
            )
            OR
            (
                spot_id IS NULL
                AND tour_spot_nearby_course_id IS NOT NULL
            )
        ),

    CONSTRAINT "CK_TOURCOURSEITEM_ORDER"
        CHECK (item_order >= 1),

    CONSTRAINT "CK_TOURCOURSEITEM_STATUS"
        CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED')),

    CONSTRAINT "CK_TOURCOURSEITEM_TRANSPORT_TYPE"
        CHECK (
            transport_type IS NULL
            OR transport_type IN ('WALK', 'BIKE', 'CAR')
        )
);

